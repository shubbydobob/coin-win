/**
 * 입력 파싱. 사용자가 타이핑한 **문자열**을 요청 본문의 수로 옮기는 유일한 자리다.
 *
 * 응답 값을 수로 되돌리는 일은 여기서 하지 않는다 — 응답은 이미 수이고, 다시 파싱한다는 것은
 * 계산에 쓰겠다는 뜻이다(§ 3). 린트가 그 둘을 디렉터리로 가른다(§ 3.1).
 *
 * 폼 상태를 문자열로 들고 있는 이유는 **입력은 제출 전까지 글자**이기 때문이다. 타이핑 도중의
 * `1.` 이나 `-` 를 수로 바꿔 두면 그 순간 커서가 튀거나 값이 사라진다.
 */

/**
 * 빈 칸과 숫자가 아닌 것은 `NaN` 이 된다. `JSON.stringify` 가 그것을 `null` 로 싣고, 서버가
 * "누락된 필드" 로 되돌려준다.
 *
 * **화면이 판정하지 않는 것이 요점이다.** 빈 칸을 0 으로 채우면 "잔고 0" 이라는 있지도 않은
 * 값이 서버에 가고, 여기서 자체 검증 문장을 지으면 도메인 규칙의 표현이 두 곳에 생긴다(§ 7).
 */
export function decimal(text: string): number {
  return text.trim() === "" ? Number.NaN : Number(text);
}
