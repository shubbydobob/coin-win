package com.coinwin.backtest.domain;

/**
 * 사이징의 기준 잔고를 무엇으로 볼 것인가. 수량이 여기서 갈린다.
 *
 * <p>둘을 함께 두는 이유는 <b>서로 다른 질문에 답하기</b> 때문이다. 하나만 있으면 전략이
 * 좋은지와 계좌가 어떻게 되는지를 구분할 수 없다.
 */
public enum CapitalMode {

    /**
     * 매 거래 초기 자본 기준. 거래 간 독립이라 거래당 손익을 서로 비교할 수 있고,
     * 전략 자체의 엣지가 순서에 가려지지 않는다.
     */
    FIXED,

    /**
     * 직전 거래까지의 자산 기준. 실사용과 같은 곡선이 나오지만, 초반 한 거래의 결과가 이후
     * 전부의 규모를 바꿔 순서 의존성이 생긴다.
     */
    COMPOUND
}
