package com.coinwin.readout.domain;

/**
 * 지표가 <b>무엇을 재는 부류인가.</b>
 *
 * <p><b>두 무리는 같은 사실에 반대 뜻을 붙인다.</b> 종가가 볼린저 상단 위에 있는 것은
 * 되돌림 무리에게는 과열이고 추세 무리에게는 돌파다. 그런데 {@link Stance} 는 둘 다
 * {@code LONG} 으로 적는다 — 그것이 정의상 맞고, 그래서 <b>다섯을 한 번에 세면 같은 사실이
 * 두 번 세어지거나 반대 사실이 상쇄된다.</b>
 *
 * <p><b>그리고 어느 무리를 읽을지가 시대에 달려 있다.</b> 연구의 안정성 분석이 2020~2023 은
 * 평균회귀, 2024~2026 은 모멘텀이고 크기가 다섯 배 다르다는 것을 찾았다. 두 무리를 하나의
 * 수로 합치는 순간 그 정보가 사라진다.
 *
 * <p><b>이 타입은 우열을 말하지 않는다.</b> 어느 무리가 옳은지는 이 저장소가 아직 재 본 적이
 * 없고, 재는 방법은 {@code docs/spec/indicator-usage.md} § 5 에 적혀 있다. 여기서 하는 일은
 * <b>합치면 안 되는 둘을 갈라 두는 것</b>뿐이다.
 *
 * <p><b>화면에 적는 말은 갖지 않는다.</b> 「추세」·「되돌림」 이라는 낱말은 번역이지 판단이
 * 아니므로 화면이 정한다({@code Stances.tsx} 의 {@code FAMILY_WORD}). 여기 두면 아무도 부르지
 * 않는 메서드가 되고, 실제로 커버리지 게이트가 그것을 잡았다.
 */
public enum IndicatorFamily {

    /** 가고 있는 쪽으로 더 간다를 재는 것들. */
    TREND,

    /** 너무 갔으면 돌아온다를 재는 것들. */
    REVERSION
}
