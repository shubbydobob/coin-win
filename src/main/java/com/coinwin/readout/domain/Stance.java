package com.coinwin.readout.domain;

/**
 * 지표가 <b>지금 어느 쪽에 서 있는가.</b>
 *
 * <p><b>유리한 쪽이 아니다.</b> 이 구분은 전부 <b>정의로 정해진다</b> — 종가가 구름 위에
 * 있다는 것, MACD 가 시그널 위에 있다는 것, RSI 가 50 을 넘는다는 것. 관측이지 예측이 아니다.
 *
 * <p>"그러니 롱이 유리하다" 는 이 타입이 말하지 않는다. 이 저장소는 그 부류의 전제를 7년
 * 15,110봉에서 반증했고({@code docs/adr/021}), {@code scope.md} 가 매수·매도 추천을 금지한다.
 * 감시 화면의 「붐비는 쪽」과 같은 태도다 — <b>세되 우열은 내지 않는다.</b>
 */
public enum Stance {
    /** 관습적으로 상승 쪽으로 읽히는 자리. */
    LONG,
    /** 하락 쪽으로 읽히는 자리. */
    SHORT,
    /** 어느 쪽도 아니다. 구름 안·밴드 안이 여기다. */
    NEUTRAL,
    /** 봉이 모자라 말할 수 없다. <b>중립과 다른 사실이다.</b> */
    UNKNOWN
}
