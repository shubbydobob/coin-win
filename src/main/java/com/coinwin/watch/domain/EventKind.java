package com.coinwin.watch.domain;

/**
 * 예정된 이벤트의 종류.
 *
 * <p>{@code QRA} 가 목록에 있는 이유가 이 모듈의 계기다 — 재무부 분기 자금조달계획에서 나온
 * 국채 바이백 확대 소식이 위험자산 급등을 만들었고, 그 급등에서 원금의 69% 가 사라졌다.
 * 그 발표는 <b>날짜가 미리 공표된다.</b> 예측할 수는 없어도 언제인지는 알 수 있다.
 */
public enum EventKind {

    /** 연준 통화정책 결정. 성명은 회의 둘째 날 오후 2시(ET)에 나온다. */
    FOMC,

    /** 미국 소비자물가지수. 오전 8시 30분(ET). */
    CPI,

    /** 재무부 분기 자금조달계획. 국채 바이백 규모가 여기서 정해진다. */
    QRA,

    /** 위 셋에 들지 않는 것. */
    OTHER
}
